import io


def clean_pdf_text(s):
    """Escape text safely for PDF string literals in standard Type 1 fonts."""
    if s is None:
        return ""
    # Convert to string, strip raw control characters except space
    text = "".join(ch if 32 <= ord(ch) <= 126 else " " for ch in str(s))
    return text.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")


def generate_pdf(title, headers, rows, subtitle=""):
    """
    Pure Python PDF 1.4 document generator.
    Produces valid, self-contained multi-page PDF bytes without external binary dependencies.
    """
    rows_per_page = 32
    row_height = 16
    chunks = [rows[i : i + rows_per_page] for i in range(0, max(1, len(rows)), rows_per_page)]
    total_pages = len(chunks)

    body = io.BytesIO()
    offsets = {}

    def write_obj(num, content_bytes):
        offsets[num] = body.tell()
        body.write(f"{num} 0 obj\n".encode("latin1"))
        body.write(content_bytes)
        body.write(b"\nendobj\n")

    cat_num = 1
    pages_num = 2
    font1_num = 3
    font2_num = 4

    page_obj_nums = []
    content_obj_nums = []
    curr_obj = 5
    for _ in range(total_pages):
        page_obj_nums.append(curr_obj)
        content_obj_nums.append(curr_obj + 1)
        curr_obj += 2

    # Obj 1: Catalog
    write_obj(cat_num, f"<< /Type /Catalog /Pages {pages_num} 0 R >>".encode("latin1"))

    # Obj 2: Pages root
    kids_str = " ".join(f"{num} 0 R" for num in page_obj_nums)
    write_obj(pages_num, f"<< /Type /Pages /Kids [{kids_str}] /Count {total_pages} >>".encode("latin1"))

    # Obj 3 & 4: Standard Base 14 Fonts (Helvetica & Helvetica-Bold)
    write_obj(font1_num, b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>")
    write_obj(font2_num, b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>")

    # Column layout
    num_cols = max(1, len(headers))
    usable_width = 532
    col_w = max(45, int(usable_width / num_cols))

    for p_idx, chunk in enumerate(chunks):
        p_num = page_obj_nums[p_idx]
        c_num = content_obj_nums[p_idx]

        # Page object
        page_dict = (
            f"<< /Type /Page /Parent {pages_num} 0 R /MediaBox [0 0 612 792] "
            f"/Contents {c_num} 0 R /Resources << /Font << /F1 {font1_num} 0 R /F2 {font2_num} 0 R >> >> >>"
        )
        write_obj(p_num, page_dict.encode("latin1"))

        # Content stream
        c_stream = io.StringIO()
        y = 740

        if p_idx == 0:
            c_stream.write(f"BT /F2 15 Tf 40 {y} Td ({clean_pdf_text(title)}) Tj ET\n")
            y -= 16
            if subtitle:
                c_stream.write(f"BT /F1 9 Tf 40 {y} Td ({clean_pdf_text(subtitle)}) Tj ET\n")
                y -= 18
        else:
            c_stream.write(f"BT /F2 11 Tf 40 {y} Td ({clean_pdf_text(title)} - Continued) Tj ET\n")
            y -= 22

        # Table Header
        c_stream.write("BT /F2 8 Tf\n")
        for c_idx, h in enumerate(headers):
            x = 40 + c_idx * col_w
            max_chars = max(4, col_w // 6)
            c_stream.write(f"1 0 0 1 {x} {y} Tm ({clean_pdf_text(h)[:max_chars]}) Tj\n")
        c_stream.write("ET\n")

        # Divider line under header
        c_stream.write(f"0.5 w 40 {y - 4} m 572 {y - 4} l S\n")
        y -= 16

        # Table Rows
        c_stream.write("BT /F1 8 Tf\n")
        for row in chunk:
            for c_idx, cell in enumerate(row):
                x = 40 + c_idx * col_w
                max_chars = max(4, col_w // 6)
                val = clean_pdf_text(cell)[:max_chars]
                c_stream.write(f"1 0 0 1 {x} {y} Tm ({val}) Tj\n")
            y -= row_height
        c_stream.write("ET\n")

        # Footer
        footer_text = f"Page {p_idx + 1} of {total_pages} - Generated by OpsDesk"
        c_stream.write(f"BT /F1 8 Tf 40 30 Td ({clean_pdf_text(footer_text)}) Tj ET\n")

        stream_bytes = c_stream.getvalue().encode("latin1", errors="replace")
        content_payload = (
            f"<< /Length {len(stream_bytes)} >>\nstream\n".encode("latin1")
            + stream_bytes
            + b"\nendstream"
        )
        write_obj(c_num, content_payload)

    # xref table
    xref_offset = body.tell()
    total_objects = curr_obj
    body.write(b"xref\n")
    body.write(f"0 {total_objects}\n".encode("latin1"))
    body.write(b"0000000000 65535 f \n")
    for num in range(1, total_objects):
        offset = offsets[num]
        body.write(f"{offset:010d} 00000 n \n".encode("latin1"))

    # trailer
    body.write(b"trailer\n")
    body.write(f"<< /Size {total_objects} /Root {cat_num} 0 R >>\n".encode("latin1"))
    body.write(f"startxref\n{xref_offset}\n%%EOF\n".encode("latin1"))

    return b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n" + body.getvalue()
