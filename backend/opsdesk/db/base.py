"""Declarative base, shared column helpers and the Fernet-encrypted JSON column type."""
from __future__ import annotations

import base64
import hashlib
import json
from datetime import datetime, timezone
from typing import Any

from cryptography.fernet import Fernet, MultiFernet
from sqlalchemy import BigInteger, DateTime, ForeignKey, Identity, MetaData, Text
from sqlalchemy.orm import DeclarativeBase, Mapped, declared_attr, mapped_column
from sqlalchemy.types import TypeDecorator

from ..settings import settings

# Deterministic constraint names so Alembic can diff and drop them reliably.
NAMING_CONVENTION = {
    "ix": "%(table_name)s_%(column_0_N_name)s_idx",
    "uq": "%(table_name)s_%(column_0_N_name)s_uniq",
    "ck": "%(table_name)s_%(constraint_name)s_chk",
    "fk": "%(table_name)s_%(column_0_name)s_fk",
    "pk": "%(table_name)s_pkey",
}


def utcnow() -> datetime:
    return datetime.now(timezone.utc)


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


def pk_column() -> Mapped[int]:
    # ``bigint GENERATED BY DEFAULT AS IDENTITY`` primary keys.
    return mapped_column(BigInteger, Identity(always=False), primary_key=True)


def created_column(index: bool = False) -> Mapped[datetime]:
    return mapped_column(DateTime(timezone=True), default=utcnow, index=index)


def updated_column() -> Mapped[datetime]:
    return mapped_column(DateTime(timezone=True), default=utcnow, onupdate=utcnow)


class TenantOwned:
    """Mixin: ``tenant_id`` FK to core_tenant, protected by row-level security."""

    @declared_attr
    def tenant_id(cls) -> Mapped[int]:
        return mapped_column(BigInteger, ForeignKey("core_tenant.id", ondelete="CASCADE"), index=True)


# --------------------------------------------------------------------------- encryption
def _fernet() -> MultiFernet:
    keys = settings.field_encryption_keys
    if not keys:
        # Development fallback derived from the JWT/app secret. Production must set
        # FIELD_ENCRYPTION_KEYS (generate with Fernet.generate_key()).
        derived = base64.urlsafe_b64encode(hashlib.sha256(settings.jwt_secret_key.encode()).digest())
        keys = [derived.decode()]
    return MultiFernet([Fernet(k.encode() if isinstance(k, str) else k) for k in keys])


def encrypt_json(value: dict | None) -> str:
    return _fernet().encrypt(json.dumps(value or {}).encode()).decode()


def decrypt_json(value: str | None) -> dict[str, Any]:
    if value in (None, ""):
        return {}
    try:
        return json.loads(_fernet().decrypt(value.encode()).decode())
    except Exception:
        return {}


class EncryptedJSON(TypeDecorator):
    """A JSON object encrypted at rest with Fernet (AES-128-CBC + HMAC), stored as TEXT.

    Supports key rotation: put the new key first in FIELD_ENCRYPTION_KEYS."""

    impl = Text
    cache_ok = True

    def process_bind_param(self, value, dialect):
        if isinstance(value, str):
            try:
                value = json.loads(value)
            except ValueError:
                value = {}
        return encrypt_json(value)

    def process_result_value(self, value, dialect):
        return decrypt_json(value)
